export function mergeFilterTexts(input: DataTableFilterTextsInput | undefined): DataTableFilterTexts {
  if (!input) return DEFAULT_FILTER_TEXTS;
  const d = DEFAULT_FILTER_TEXTS;
  return {
    ...d,
    ...input,
    operators: { ...d.operators, ...input.operators },
    dateOperators: { ...d.dateOperators, ...input.dateOperators },
    errors: { ...d.errors, ...input.errors },
    presets: { ...d.presets, ...input.presets },
    help: { ...d.help, ...input.help },
  };
}
